export type MessageKey = keyof typeof I18N.zh;

const LANG_KEY = "lm.lang";
export type Lang = "zh" | "en";

export function storedLang(): Lang {
  return localStorage.getItem(LANG_KEY) === "en" ? "en" : "zh";
}

export function persistLang(next: Lang): void {
  localStorage.setItem(LANG_KEY, next);
  document.documentElement.lang = next === "zh" ? "zh-Hant" : "en";
}

/** The language `t()` reads. Kept in a module variable, not React state, because
 *  api.ts formats error messages outside any component tree. `LanguageProvider` keeps
 *  the two in step. */
let current: Lang = storedLang();
export function setActiveLang(next: Lang): void {
  current = next;
}

export const locale = (): string => (current === "en" ? "en-US" : "zh-TW");

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  let s: string = I18N[current][key] ?? I18N.zh[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}
